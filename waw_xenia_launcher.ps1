# Windows PowerShell 5.1; standalone configuration and MP launcher, no Python.
[CmdletBinding()]
param(
    [Parameter(Position=0)][ValidateSet('setup', 'launch', 'show')][string]$Action = 'setup',
    [string]$Exe, [string]$Game, [string]$Server, [string]$Settings,
    [switch]$Yes
)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

function Get-ApiUrl([string]$Value) {
    $Value = $Value.Trim()
    if (-not $Value -or $Value -match '[\s\\,"\x00-\x1f]') { throw 'Enter a server IP/hostname or HTTP(S) API URL.' }
    if (-not $Value.Contains('://')) { $Value = 'http://' + $Value + ':8081/xenia/' }
    $uri = $null
    if (-not [Uri]::TryCreate($Value, [UriKind]::Absolute, [ref]$uri) -or
        $uri.Scheme -notin @('http', 'https') -or -not $uri.Host -or
        $uri.UserInfo -or $uri.Query -or $uri.Fragment -or $uri.Port -lt 1) {
        throw 'Enter an HTTP(S) API URL without credentials, query or fragment.'
    }
    return $Value.TrimEnd('/') + '/'
}

function Read-GeneratedConfig([string]$Text) {
    # Accept Xenia's flat tables and single-line scalars, not arbitrary TOML.
    # Unsupported syntax is rejected before editing (including multiline strings).
    $tables = [Collections.Generic.Dictionary[string,object]]::new([StringComparer]::Ordinal)
    $section = ''
    $lineNumber = 0
    $lines = [Collections.Generic.List[object]]::new()
    foreach ($match in [regex]::Matches($Text, '[^\r\n]*(?:\r\n|\n|\r|$)')) {
        $line = $match.Value
        if (-not $line) { continue }
        $lineNumber++
        $body = $line.TrimEnd("`r", "`n")
        $record = @{ Raw=$line; Section=$section; Key=''; Prefix=''; Suffix=''; Ending=$line.Substring($body.Length); Header=$false }
        if ($body -cmatch '^\s*\[([A-Za-z_][A-Za-z0-9_]*(?:\.[A-Za-z_][A-Za-z0-9_]*)*)\]\s*(?:#.*)?$') {
            $section = $Matches[1]
            if ($tables.ContainsKey($section)) { throw "Duplicate TOML table [$section]; config untouched." }
            $tables.Add($section, [Collections.Generic.Dictionary[string,string]]::new([StringComparer]::Ordinal))
            $record.Section = $section
            $record.Header = $true
        } elseif ($body -notmatch '^\s*(?:#.*)?$') {
            $scalar = '^([ \t]*([A-Za-z_][A-Za-z0-9_]*)[ \t]*=[ \t]*)("(?:[^"\\\x00-\x1f]|\\(?:["\\bfnrt]|u[0-9a-fA-F]{4}))*"|true|false|[+-]?(?:0|[1-9][0-9]*)(?:\.[0-9]+)?(?:[eE][+-]?[0-9]+)?|0x[0-9a-fA-F]+|[+-]?(?:inf|nan))([ \t]*(?:#.*)?)$'
            $valueMatch = [regex]::Match($body, $scalar)
            if (-not $section -or -not $valueMatch.Success) { throw "Unsupported TOML formatting at line $lineNumber. Use the flat config generated by Xenia; config untouched." }
            $key = $valueMatch.Groups[2].Value
            if ($tables[$section].ContainsKey($key)) { throw "Duplicate TOML key $section.$key; config untouched." }
            $tables[$section].Add($key, $valueMatch.Groups[3].Value)
            $record.Key = $key
            $record.Prefix = $valueMatch.Groups[1].Value
            $record.Suffix = $valueMatch.Groups[4].Value
        }
        $lines.Add($record)
    }
    return @{ Tables=$tables; Lines=$lines }
}

function Update-LiveConfig([string]$Text, [string]$Endpoint) {
    $parsed = Read-GeneratedConfig $Text
    $values = [ordered]@{api_address=('"' + $Endpoint + '"'); api_list=('"' + $Endpoint + ',"'); network_mode='2'; xstorage_backend='true'}
    $newline = "`n"
    if ($Text.Contains("`r`n")) { $newline = "`r`n" }
    $output = [Text.StringBuilder]::new()
    $seen = [Collections.Generic.HashSet[string]]::new([StringComparer]::Ordinal)
    $inside = $false
    foreach ($line in $parsed.Lines) {
        if ($line.Header) {
            if ($inside) {
                foreach ($key in $values.Keys) {
                    if (-not $seen.Contains($key)) { [void]$output.Append("$key = $($values[$key])$newline") }
                }
            }
            $inside = $line.Section -ceq 'Live'
        }
        if ($inside -and $line.Key -cin @($values.Keys)) {
            [void]$seen.Add($line.Key)
            [void]$output.Append($line.Prefix + $values[$line.Key] + $line.Suffix + $line.Ending)
        } else { [void]$output.Append($line.Raw) }
    }
    if ($inside -or -not $parsed.Tables.ContainsKey('Live')) {
        if ($output.Length -gt 0 -and $output[$output.Length-1] -ne "`n") { [void]$output.Append($newline) }
        if (-not $parsed.Tables.ContainsKey('Live')) { [void]$output.Append($newline + '[Live]' + $newline) }
        foreach ($key in $values.Keys) {
            if (-not $seen.Contains($key)) { [void]$output.Append("$key = $($values[$key])$newline") }
        }
    }
    $result = $output.ToString()
    $null = Read-GeneratedConfig $result
    return $result
}

function Assert-XeniaStopped {
    $running = @(Get-Process | Where-Object { $_.ProcessName -like 'xenia*' })
    if ($running.Count -gt 0) { throw 'Close Xenia first so it cannot overwrite its config, then retry.' }
}

function Write-AtomicFile([string]$Path, [byte[]]$Bytes, [switch]$Backup) {
    $parent = [IO.Path]::GetDirectoryName($Path)
    [void][IO.Directory]::CreateDirectory($parent)
    $temporary = Join-Path $parent ([IO.Path]::GetRandomFileName())
    try {
        [IO.File]::WriteAllBytes($temporary, $Bytes)
        if ([IO.File]::Exists($Path)) {
            $backupPath = [NullString]::Value
            if ($Backup) { $backupPath = $Path + '.' + [Guid]::NewGuid().ToString('N') + '.bak' }
            [IO.File]::Replace($temporary, $Path, $backupPath)
            if ($backupPath) { Write-Host "Original configuration backed up: $backupPath" }
        } else { [IO.File]::Move($temporary, $Path) }
    } finally { if ([IO.File]::Exists($temporary)) { [IO.File]::Delete($temporary) } }
}

function Select-ExistingFile([string]$Label, [string]$Filename) {
    Add-Type -AssemblyName System.Windows.Forms
    $dialog = New-Object System.Windows.Forms.OpenFileDialog
    try {
        $dialog.Title = $Label
        $dialog.Filter = "$Filename|$Filename"
        if ($dialog.ShowDialog() -ne [Windows.Forms.DialogResult]::OK) { throw 'File selection cancelled. No settings changed.' }
        return $dialog.FileName
    } finally { $dialog.Dispose() }
}

function Invoke-XeniaLauncher {
    $repo = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..\..'))
    $inRepo = Test-Path -LiteralPath (Join-Path $repo 'WaW_Server_Control.bat') -PathType Leaf
    $settingsPath = $Settings
    if (-not $settingsPath) {
        $settingsPath = Join-Path $PSScriptRoot 'settings.local.json'
        if ($inRepo) { $settingsPath = Join-Path $repo 'tmp\waw-xenia-launcher.json' }
    }
    $settingsPath = [IO.Path]::GetFullPath($settingsPath)
    $chosen = @{exe=''; game=''; api='http://157.230.65.227:8081/xenia/'}
    if (Test-Path -LiteralPath $settingsPath -PathType Leaf) {
        $saved = [IO.File]::ReadAllText($settingsPath) | ConvertFrom-Json
        foreach ($key in @('exe','game','api')) {
            if (-not $saved.PSObject.Properties[$key] -or $saved.$key -isnot [string]) { throw "Invalid saved setting: $key" }
            $chosen[$key] = $saved.$key
        }
    }
    if ($Exe) { $chosen.exe = $Exe }
    if ($Game) { $chosen.game = $Game }
    if ($Server) { $chosen.api = $Server }
    if ($Action -eq 'setup' -and -not $Yes) {
        $answer = Read-Host "Server IP or full API URL [$($chosen.api)]"
        if ($answer.Trim()) { $chosen.api = $answer.Trim() }
        foreach ($key in @('exe','game')) {
            $filename = 'default_mp.xex'
            if ($key -eq 'exe') { $filename = 'xenia_canary_netplay.exe' }
            $answer = Read-Host "$filename path [$($chosen[$key])] (Enter keeps saved path or opens file picker)"
            if ($answer.Trim()) { $chosen[$key] = $answer.Trim().Trim('"') }
            if (-not $chosen[$key]) { $chosen[$key] = Select-ExistingFile "Select $filename" $filename }
        }
    }
    $chosen.api = Get-ApiUrl $chosen.api
    foreach ($key in @('exe','game')) {
        if (-not $chosen[$key]) { throw 'Run configure_waw_xenia.bat first to choose your emulator and game.' }
        $chosen[$key] = [IO.Path]::GetFullPath($chosen[$key])
        $name = 'default_mp.xex'
        if ($key -eq 'exe') { $name = 'xenia_canary_netplay.exe' }
        if ([IO.Path]::GetFileName($chosen[$key]) -ine $name -or -not [IO.File]::Exists($chosen[$key])) { throw "Select the existing $name file." }
    }
    $emulatorDir = [IO.Path]::GetDirectoryName($chosen.exe)
    $config = Join-Path $emulatorDir 'xenia-canary-netplay.config.toml'
    if ($settingsPath -in @($config, $chosen.exe, $chosen.game, (Join-Path $emulatorDir 'portable.txt'))) {
        throw 'Launcher settings must use a separate JSON file, not an emulator or game file.'
    }
    if (-not [IO.File]::Exists((Join-Path $emulatorDir 'portable.txt')) -or -not [IO.File]::Exists($config)) {
        throw 'Use an initialized portable Netplay installation: portable.txt and xenia-canary-netplay.config.toml beside the EXE. Open and close Xenia once to generate its config.'
    }
    $encoding = [Text.UTF8Encoding]::new($false, $true)
    $original = [IO.File]::ReadAllBytes($config)
    $text = $encoding.GetString($original)
    $bom = $text.StartsWith([string][char]0xfeff, [StringComparison]::Ordinal)
    if ($bom) { $text = $text.Substring(1) }
    $parsed = Read-GeneratedConfig $text
    if ($parsed.Tables.ContainsKey('Storage') -and $parsed.Tables['Storage'].ContainsKey('storage_root')) {
        $raw = $parsed.Tables['Storage']['storage_root']
        if (-not $raw.StartsWith('"')) { throw 'Unsupported storage_root; config untouched.' }
        $storage = ConvertFrom-Json $raw
        if ($storage) {
            if (-not [IO.Path]::IsPathRooted($storage)) { $storage = Join-Path $emulatorDir $storage }
            if ([IO.Path]::GetFullPath($storage).TrimEnd('\','/') -ine $emulatorDir.TrimEnd('\','/')) { throw 'Config storage_root points elsewhere; use that installation instead.' }
        }
    }
    Write-Host "Server API: $($chosen.api)`nXenia: $($chosen.exe)`nMultiplayer: $($chosen.game)`nConfig: $config"
    if ($Action -eq 'show') { return }
    Assert-XeniaStopped
    $updated = Update-LiveConfig $text $chosen.api
    if ($bom) { $updated = [string][char]0xfeff + $updated }
    $bytes = $encoding.GetBytes($updated)
    if ([Convert]::ToBase64String($bytes) -cne [Convert]::ToBase64String($original)) {
        Write-AtomicFile $config $bytes -Backup
    }
    Write-AtomicFile $settingsPath $encoding.GetBytes(($chosen | ConvertTo-Json) + "`n")
    Write-Host "Saved launcher settings: $settingsPath"
    if ($Action -eq 'launch') {
        $process = Start-Process -FilePath $chosen.exe -ArgumentList ('"' + $chosen.game + '"') -WorkingDirectory $emulatorDir -PassThru
        Write-Host "Launched WaW multiplayer (PID $($process.Id))."
    } else { Write-Host 'Ready. Double-click launch_waw_xenia.bat to play.' }
}

if ($MyInvocation.InvocationName -ne '.') {
    try { Invoke-XeniaLauncher; exit 0 }
    catch { Write-Host "Error: $($_.Exception.Message)"; exit 1 }
}
